def tokens(s):
    s = re.sub(r"<[^>]*>|\[[^\]]*\]|\{[^}]*\}", " ", s or "")
    s = norm(s).replace("-", " ")
    strip = lambda x: re.sub(r"^[^\u0900-\u097F\w]+|[^\u0900-\u097F\w]+$", "", x).strip("\u0964\u0965")
    return [t for t in (strip(x) for x in s.split()) if t]

def match(text):
    """-> list of (class_id, marker_label) for one utterance."""
    tk, out, used = tokens(text), [], set()
    for j in range(len(tk)):
        t, nxt = tk[j], (tk[j + 1] if j + 1 < len(tk) else None)
        if j + 1 < len(tk):
            if t in STEMS and nxt in LIGHTV: out.append((18, f"{t} {nxt}")); used.update((j, j + 1))
            if t in LNOUN and nxt in LVERB: out.append((18, f"{t} {nxt}")); used.update((j, j + 1))
            if t in PASSP and nxt in JAF: out.append((16, f"{t} {nxt}"))
